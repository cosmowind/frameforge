#!/usr/bin/env node
/**
 * hmd_to_mcap.js — Convert a Galaxea `.hmd` stereo session folder into a single
 * Foxglove MCAP file conforming to the vendor-facing MCAP delivery spec
 * (see `MCAP 交付规范（供应商版）.md`).
 *
 * Business boundary: this script is the SUBMISSION-side conversion. It parses
 * the Galaxea .hmd wire format directly (without going through the project's
 * local-preview tooling `static/hmd/hmd-decode.esm.js`) so that the local
 * preview pipeline stays completely independent of the upload pipeline.
 *
 * .hmd wire format (Galaxea):
 *   Real HMD3 packet headers:
 *     - 0x59 (IMU, fixed 97 bytes total)
 *     - 0x5a (Galaxea glue, 8-byte header)
 *     - 0xfd (per-GOP HEVC chunk, 27-byte header + VPS/SPS/PPS/IDR/P-frames)
 *   All other "HMD3" sequences (76k+ in 256 MB) are HEVC-payload noise —
 *   scan only at packet boundaries (8/27-byte header validation). HEVC
 *   bitstream lives between/below the packet headers; concatenating gives the
 *   full 60 fps frame-interleaved stereo bitstream (even = camera 0 / left
 *   eye, odd = camera 1 / right eye).
 *
 * Pipeline:
 *   1. Read every part_NNN.hmd file in the session dir.
 *   2. Walk each part's bytes, find real packet headers, capture HEVC bytes
 *      between them, and capture IMU packets.
 *   3. Split the concatenated HEVC into per-eye bitstreams + parameter sets.
 *   4. Write MCAP using @mcap/core. Topics follow the vendor delivery spec:
 *        - /top-left-camera/image-raw   foxglove.CompressedVideo
 *        - /top-right-camera/image-raw  foxglove.CompressedVideo
 *        - /head-imu                    google.protobuf.StringValue (JSON)
 *      The descriptor bytes (COMPRESSED_VIDEO_FDS / STRING_VALUE_FDS) are
 *      lifted from frameforge upstream `lib/mcap/proto.ts` so Foxglove Studio
 *      can interpret them — same as the browser-side converter.
 *   5. Copy metadata.json next to the MCAP as <out>.metadata.json — frameforge
 *      expects metadata.json as a separate S3 object under the session.
 *
 * CLI:
 *   node hmd_to_mcap.js \
 *     --parts-glob '<session>/part_*.hmd' \
 *     --metadata   '<session>/metadata.json' \
 *     --out        '<temp>.mcap'
 *
 * Output:
 *   - <out>                              — MCAP file
 *   - <out>.metadata.json                — copy of the input metadata.json
 *   - stdout: JSON { ok: true, mcap: <path>, metadata: <path>, stats: {...} }
 */

'use strict';

const fs = require('fs');
const path = require('path');
const protobuf = require('protobufjs');
const { McapWriter, TempBuffer } = require('@mcap/core');

// ---------------------------------------------------------------------------
// CLI parsing
// ---------------------------------------------------------------------------

function parseArgs(argv) {
  const args = {};
  for (let i = 2; i < argv.length; i++) {
    const k = argv[i];
    if (k === '--parts-glob') args.partsGlob = argv[++i];
    else if (k === '--metadata') args.metadata = argv[++i];
    else if (k === '--out') args.out = argv[++i];
    else if (k === '--session-dir') args.sessionDir = argv[++i];
    else if (k === '--help' || k === '-h') {
      console.log(
        'hmd_to_mcap.js --parts-glob "<dir>/part_*.hmd" --metadata <m.json> --out <out.mcap>',
      );
      process.exit(0);
    }
  }
  return args;
}

// ---------------------------------------------------------------------------
// Galaxea .hmd packet format constants
// ---------------------------------------------------------------------------

// "HMD3" magic — 4 ASCII bytes. Note: the same 4 bytes interpreted as a
// little-endian u32 give 0x33494D55, matching the frameforge upstream
// parser's MAGIC. Either interpretation yields the same byte sequence;
// we just walk bytes here so we never need to decode-as-int.
const MAGIC = [0x55, 0x4d, 0x49, 0x33];
const IMU_TYPE = 0x59;       // 89 — IMU packet, fixed 97 bytes total
const GLUE_TYPE = 0x5a;      // 90 — Galaxea glue, 8-byte header
const CHUNK_TYPE = 0xfd;     // 253 — HEVC GOP chunk, 27-byte header
const HEADER_LEN = 8;
const IMU_TOTAL = 97;
const GLUE_HEADER = 8;
const CHUNK_HEADER = 27;


function b64ToBytes(b64) {
  return new Uint8Array(Buffer.from(b64, 'base64'));
}

const COMPRESSED_VIDEO_FDS = b64ToBytes(COMPRESSED_VIDEO_FDS_B64);
const STRING_VALUE_FDS = b64ToBytes(STRING_VALUE_FDS_B64);
const COMPRESSED_VIDEO_SCHEMA_NAME = 'foxglove.CompressedVideo';
const STRING_VALUE_SCHEMA_NAME = 'google.protobuf.StringValue';

// ---------------------------------------------------------------------------
// Protobuf message encoders (inline, identical shape to frameforge proto.ts)
// ---------------------------------------------------------------------------

const messageRoot = protobuf.parse(
  `syntax = "proto3";
   package umiconv;
   message Timestamp { int64 seconds = 1; int32 nanos = 2; }
   message CompressedVideo {
     Timestamp timestamp = 1;
     string frame_id = 2;
     bytes data = 3;
     string format = 4;
   }
   message StringValue { string value = 1; }`,
  { keepCase: true },
).root;
messageRoot.resolveAll();

const CompressedVideoType = messageRoot.lookupType('umiconv.CompressedVideo');
const StringValueType = messageRoot.lookupType('umiconv.StringValue');

function encodeCompressedVideo({ tsUs, frameId, h265 }) {
  const seconds = Math.floor(tsUs / 1_000_000);
  const nanos = (tsUs % 1_000_000) * 1000;
  return CompressedVideoType.encode(
    CompressedVideoType.create({
      timestamp: { seconds, nanos },
      frame_id: frameId,
      data: h265,
      format: 'h265',
    }),
  ).finish();
}

function encodeStringValue(obj) {
  return StringValueType.encode(StringValueType.create({ value: JSON.stringify(obj) })).finish();
}

// ---------------------------------------------------------------------------
// HEVC helpers
// ---------------------------------------------------------------------------

const SC4 = [0x00, 0x00, 0x00, 0x01];

function* iterateNals(data) {
  for (let i = 0; i + 4 < data.byteLength; i++) {
    if (data[i] === SC4[0] && data[i + 1] === SC4[1] && data[i + 2] === SC4[2] && data[i + 3] === SC4[3]) {
      const nalType = (data[i + 4] >> 1) & 0x3f;
      yield [nalType, i];
      i += 3;
    }
  }
}

// ---------------------------------------------------------------------------
// Galaxea .hmd parser (inline — no dependency on local-preview tooling)
// ---------------------------------------------------------------------------

/**
 * Walk a single part buffer and yield {offset, type} for every real packet.
 * Validation per-type: IMU/GLUE bytes 5-7 are 0; CHUNK bytes 6-9 are 0x00 0x00
 * 0x86 0x01 (GOP magic). This rejects the 76k+ "HMD3" sequences that live
 * inside HEVC payload noise.
 */
function findPackets(buf) {
  const real = [];
  for (let p = 0; p + HEADER_LEN <= buf.length; p++) {
    if (buf[p] !== MAGIC[0] || buf[p + 1] !== MAGIC[1] ||
        buf[p + 2] !== MAGIC[2] || buf[p + 3] !== MAGIC[3]) continue;
    const t = buf[p + 4];
    if (t === IMU_TYPE || t === GLUE_TYPE) {
      if (buf[p + 5] === 0 && buf[p + 6] === 0 && buf[p + 7] === 0) {
        real.push({ offset: p, type: t });
      }
    } else if (t === CHUNK_TYPE) {
      if (buf[p + 6] === 0 && buf[p + 7] === 0 &&
          buf[p + 8] === 0x86 && buf[p + 9] === 0x01) {
        real.push({ offset: p, type: t });
      }
    }
  }
  return real;
}

/**
 * Parse a session: given an ordered list of part file paths (already sorted by
 * index), return { hevc, imu } where hevc is the concatenated HEVC byte stream
 * (Annex-B NAL units) and imu is an array of { seq, t_us, raw } packets.
 *
 * The HEVC bytes come from two regions per part:
 *   - "Gap" regions: bytes between HMD3 packet headers
 *   - "0xfd payload": bytes inside 0xfd packets, after the 27-byte header
 */
function parseSession(partFilePaths) {
  const buffers = partFilePaths.map((p) => new Uint8Array(fs.readFileSync(p)));
  const offsets = [];
  let totalLen = 0;
  for (const b of buffers) {
    offsets.push(totalLen);
    totalLen += b.length;
  }

  function locate(off) {
    let lo = 0, hi = offsets.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (offsets[mid] <= off) lo = mid; else hi = mid - 1;
    }
    return { buf: buffers[lo], localOff: off - offsets[lo] };
  }

  function pushRange(chunks, start, end, locateFn) {
    if (start >= end) return;
    const a = locateFn(start);
    if (a.localOff + (end - start) <= a.buf.length) {
      chunks.push(a.buf.subarray(a.localOff, a.localOff + (end - start)));
      return;
    }
    // Region spans part boundaries: copy in two+ slices.
    let cursor = start;
    while (cursor < end) {
      const loc = locateFn(cursor);
      const take = Math.min(loc.buf.length - loc.localOff, end - cursor);
      chunks.push(loc.buf.subarray(loc.localOff, loc.localOff + take));
      cursor += take;
    }
  }

  // Collect all packets across parts in offset order.
  const allPackets = [];
  for (let pi = 0; pi < buffers.length; pi++) {
    const local = findPackets(buffers[pi]);
    for (const p of local) {
      allPackets.push({ offset: p.offset + offsets[pi], type: p.type });
    }
  }
  allPackets.sort((a, b) => a.offset - b.offset);

  const hevcChunks = [];
  const imu = [];
  let cursor = 0;
  for (let i = 0; i < allPackets.length; i++) {
    const pkt = allPackets[i];
    const p = pkt.offset;
    let pktEnd;
    if (pkt.type === IMU_TYPE) pktEnd = p + IMU_TOTAL;
    else if (pkt.type === GLUE_TYPE) pktEnd = p + GLUE_HEADER;
    else if (pkt.type === CHUNK_TYPE) pktEnd = allPackets[i + 1] ? allPackets[i + 1].offset : totalLen;
    else pktEnd = p + HEADER_LEN;

    // Gap region between previous cursor and this packet header → HEVC bytes.
    if (p > cursor) {
      pushRange(hevcChunks, cursor, p, locate);
    }

    if (pkt.type === IMU_TYPE) {
      const loc = locate(p);
      const buf = loc.buf;
      const lo = loc.localOff + HEADER_LEN;
      const seq = buf[lo + 8] | (buf[lo + 9] << 8) | (buf[lo + 10] << 16) | (buf[lo + 11] << 24);
      const tLow = buf[lo + 12] | (buf[lo + 13] << 8) | (buf[lo + 14] << 16);
      imu.push({ seq, t_us: tLow, raw: buf.subarray(lo, lo + (IMU_TOTAL - HEADER_LEN)) });
    } else if (pkt.type === GLUE_TYPE) {
      const hevcStart = p + GLUE_HEADER;
      if (hevcStart < pktEnd) pushRange(hevcChunks, hevcStart, pktEnd, locate);
    } else if (pkt.type === CHUNK_TYPE) {
      const hevcStart = p + CHUNK_HEADER;
      if (hevcStart < pktEnd) pushRange(hevcChunks, hevcStart, pktEnd, locate);
    }
    cursor = pktEnd;
  }
  if (cursor < totalLen) pushRange(hevcChunks, cursor, totalLen, locate);

  // Concat HEVC chunks.
  let total = 0;
  for (const c of hevcChunks) total += c.length;
  const hevc = new Uint8Array(total);
  let off = 0;
  for (const c of hevcChunks) {
    hevc.set(c, off);
    off += c.length;
  }

  return { hevc, imu };
}

/**
 * Capture VPS / SPS / PPS NAL units from the front of the concatenated HEVC.
 * Each .hmd session typically emits VPS+SPS+PPS once at the start; we capture
 * them once and prepend them to each eye so either eye is independently
 * decodable.
 */
function captureParams(hevc) {
  const params = { vps: null, sps: null, pps: null };
  const nalStarts = [];
  for (const [, off] of iterateNals(hevc)) nalStarts.push(off);
  nalStarts.push(hevc.byteLength);
  for (let k = 0; k + 1 < nalStarts.length; k++) {
    const a = nalStarts[k];
    const b = nalStarts[k + 1];
    if (a + 4 >= hevc.byteLength) break;
    const nalType = (hevc[a + 4] >> 1) & 0x3f;
    if (nalType === 32 && !params.vps) params.vps = hevc.subarray(a, b);
    else if (nalType === 33 && !params.sps) params.sps = hevc.subarray(a, b);
    else if (nalType === 34 && !params.pps) params.pps = hevc.subarray(a, b);
    if (params.vps && params.sps && params.pps) break;
  }
  return params;
}

/**
 * Split a 60 fps frame-interleaved HEVC bitstream into per-eye access units.
 * Even-indexed frames → left, odd → right. Parameter sets (VPS/SPS/PPS, nal
 * types 32/33/34) go to BOTH eyes so each side is independently decodable.
 * Returns { leftFrames: Uint8Array[], rightFrames: Uint8Array[] } where each
 * element is one slice between two consecutive start codes.
 */
function splitStereoFrames(hevc, params) {
  const offsets = [];
  for (const [, off] of iterateNals(hevc)) offsets.push(off);
  offsets.push(hevc.byteLength);

  const left = [];
  const right = [];
  let frameIdx = 0;
  for (let k = 0; k + 1 < offsets.length; k++) {
    const a = offsets[k];
    const nalType = (hevc[a + 4] >> 1) & 0x3f;
    const isParamSet = nalType === 32 || nalType === 33 || nalType === 34;
    const slice = hevc.subarray(a, offsets[k + 1]);
    if (isParamSet) {
      // Prepend VPS/SPS/PPS once at the very front of each eye's stream.
      if (frameIdx === 0 || left.length === 0) {
        if (params.vps) left.push(params.vps);
        if (params.sps) left.push(params.sps);
        if (params.pps) left.push(params.pps);
        if (params.vps) right.push(params.vps);
        if (params.sps) right.push(params.sps);
        if (params.pps) right.push(params.pps);
      }
      continue;
    }
    if (frameIdx % 2 === 0) left.push(slice);
    else right.push(slice);
    frameIdx++;
  }
  return { leftFrames: left, rightFrames: right };
}

// ---------------------------------------------------------------------------
// Globbing (tiny impl — no extra dep)
// ---------------------------------------------------------------------------

function globParts(pattern) {
  const m = pattern.match(/^(.*?)\/part_\*\.hmd$/);
  if (!m) throw new Error(`parts-glob must match <dir>/part_*.hmd (got: ${pattern})`);
  const dir = m[1];
  const entries = fs.readdirSync(dir);
  return entries
    .filter((f) => /^part_\d+\.hmd$/i.test(f))
    .sort((a, b) => {
      const na = parseInt(a.match(/part_(\d+)/i)[1], 10);
      const nb = parseInt(b.match(/part_(\d+)/i)[1], 10);
      return na - nb;
    })
    .map((f) => path.join(dir, f));
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const args = parseArgs(process.argv);
  if (!args.out) throw new Error('--out is required');
  if (!args.partsGlob && !args.sessionDir) {
    throw new Error('--parts-glob or --session-dir is required');
  }

  const partsGlob = args.partsGlob || `${args.sessionDir}/part_*.hmd`;
  const partFiles = globParts(partsGlob);
  if (partFiles.length === 0) {
    throw new Error(`No part_*.hmd files matching ${partsGlob}`);
  }
  process.stderr.write(`[hmd_to_mcap] found ${partFiles.length} .hmd parts\n`);

  // 1. Parse .hmd → HEVC + IMU (inline parser, no external dep).
  const parsed = parseSession(partFiles);
  process.stderr.write(
    `[hmd_to_mcap] parse done: hevc=${parsed.hevc.byteLength} bytes, ` +
    `imu=${parsed.imu.length} packets\n`,
  );

  // 2. Capture VPS/SPS/PPS, then split stereo → left/right frames.
  const params = captureParams(parsed.hevc);
  process.stderr.write(
    `[hmd_to_mcap] params: vps=${params.vps ? 'yes' : 'no'}, ` +
    `sps=${params.sps ? 'yes' : 'no'}, pps=${params.pps ? 'yes' : 'no'}\n`,
  );
  const { leftFrames, rightFrames } = splitStereoFrames(parsed.hevc, params);
  process.stderr.write(
    `[hmd_to_mcap] split: left=${leftFrames.length} frames, right=${rightFrames.length} frames\n`,
  );

  // 3. Write MCAP.
  const buf = new TempBuffer();
  const writer = new McapWriter({ writable: buf, useChunks: true });
  await writer.start({ profile: '', library: 'vendor-upload-pkg' });

  const videoSchemaId = await writer.registerSchema({
    name: COMPRESSED_VIDEO_SCHEMA_NAME,
    encoding: 'protobuf',
    data: COMPRESSED_VIDEO_FDS,
  });
  const stringSchemaId = await writer.registerSchema({
    name: STRING_VALUE_SCHEMA_NAME,
    encoding: 'protobuf',
    data: STRING_VALUE_FDS,
  });

  const channelIds = new Map();
  async function channelFor(topic, schemaId) {
    if (channelIds.has(topic)) return channelIds.get(topic);
    const id = await writer.registerChannel({
      schemaId,
      topic,
      messageEncoding: 'protobuf',
      metadata: new Map(),
    });
    channelIds.set(topic, id);
    return id;
  }

  let seq = 0;

  // Derive per-frame timestamps. .hmd recordings don't carry per-frame ts
  // (only IMU packets have t_us), so we distribute frames evenly between the
  // first and last IMU sample. Falls back to a 30 s / 60 fps assumption when
  // IMU is missing.
  const fps = 60;
  let t0Us, t1Us;
  if (parsed.imu.length >= 2) {
    t0Us = parsed.imu[0].t_us;
    t1Us = parsed.imu[parsed.imu.length - 1].t_us;
  } else {
    t0Us = 0;
    t1Us = 30 * 1_000_000;
  }
  const totalFrames = Math.max(leftFrames.length, rightFrames.length);
  const stepUs = totalFrames > 1
    ? Math.max(1, Math.floor((t1Us - t0Us) / totalFrames))
    : Math.floor(1e6 / fps);

  async function writeEye(topic, frames, frameId) {
    const channelId = await channelFor(topic, videoSchemaId);
    for (let i = 0; i < frames.length; i++) {
      const tsUs = t0Us + i * stepUs;
      await writer.addMessage({
        channelId,
        sequence: seq++,
        logTime: BigInt(tsUs) * 1000n,
        publishTime: BigInt(tsUs) * 1000n,
        data: encodeCompressedVideo({ tsUs, frameId, h265: frames[i] }),
      });
    }
  }

  // Topic names follow the vendor-facing MCAP delivery spec.
  await writeEye('/top-left-camera/image-raw', leftFrames, 'top_left_camera');
  await writeEye('/top-right-camera/image-raw', rightFrames, 'top_right_camera');

  // IMU messages — one JSON-encoded StringValue per IMU packet, on the
  // /head-imu topic from the vendor spec. Each packet carries seq + t_us
  // extracted inline + the raw payload as base64 (downstream decodes).
  const imuChannel = await channelFor('/head-imu', stringSchemaId);
  for (const imu of parsed.imu) {
    await writer.addMessage({
      channelId: imuChannel,
      sequence: seq++,
      logTime: BigInt(imu.t_us) * 1000n,
      publishTime: BigInt(imu.t_us) * 1000n,
      data: encodeStringValue({
        seq: imu.seq,
        t_us: imu.t_us,
        raw_b64: Buffer.from(imu.raw).toString('base64'),
      }),
    });
  }

  await writer.end();

  // 4. Flush MCAP bytes to disk.
  const mcapBytes = buf.get();
  fs.writeFileSync(args.out, mcapBytes);

  // 5. Copy metadata.json next to the MCAP if available.
  let metaOut = null;
  if (args.metadata && fs.existsSync(args.metadata)) {
    metaOut = args.out + '.metadata.json';
    fs.copyFileSync(args.metadata, metaOut);
  }

  process.stdout.write(
    JSON.stringify({
      ok: true,
      mcap: args.out,
      metadata: metaOut,
      stats: {
        parts: partFiles.length,
        leftFrames: leftFrames.length,
        rightFrames: rightFrames.length,
        imuPackets: parsed.imu.length,
        bytes: mcapBytes.byteLength,
      },
    }) + '\n',
  );
}

main().catch((err) => {
  process.stderr.write(`[hmd_to_mcap] FATAL: ${err && err.stack ? err.stack : err}\n`);
  process.exit(1);
});